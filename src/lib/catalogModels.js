/**
 * catalogModels.js
 * Extra models for brands that are already on the shelf.
 *
 * catalog.js owns the original Brick City products (including day-one
 * Mount to Coast H1 trail, H1 backyard, and C1 marathon) and the rules
 * that decide which city unlocks a product. This file is only more
 * models. Prefer a brand the game already sells in that style. Set
 * `unlock` to a city id from constants.js.
 *
 * Why the stats stay inside the old ranges: a later shoe can be a better
 * mix (more miles, less of a penalty) and it can cost more, but it cannot
 * invent a pace bonus the original rack never had. The tests check that.
 * Summit Hollow is the expensive town, so its sticker price sits above
 * the old maximum. The pace numbers do not.
 *
 * Real product names are used only when they are the actual shoe, vest,
 * gel, or hat. Anything else is a plain description ("Yard Day", "Summit
 * Belt") so it is obvious the name is the game's, not a fake model code.
 * Colors, when a hat or sock has one, are brand colors. There are no logos.
 */

function shoe(id, name, brand, style, price, maxMiles, unlock, blurb, mods) {
  return { id, name, brand, style, price, maxMiles, unlock, blurb, mods };
}

function carry(id, name, brand, kind, price, unlock, blurb, shortRoad) {
  return { id, name, brand, kind, price, unlock, blurb, shortRoad };
}

function sock(id, name, brand, price, unlock, ultraFatigueCut, blisterShield, color, blurb) {
  return { id, name, brand, price, unlock, ultraFatigueCut, blisterShield, color, blurb };
}

function hat(id, name, brand, price, unlock, heatCut, colorKey, blurb) {
  return { id, name, brand, price, unlock, heatCut, colorKey, blurb };
}

function fuel(id, name, brand, kind, price, unlock, blurb, lines) {
  return { id, name, brand, kind, price, unlock, blurb, lines };
}

